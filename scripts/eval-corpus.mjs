// Measures per-rule precision/recall on corpus/ (real files via labels.json, fixtures via inline `// expect:` markers).
import fs from 'node:fs';
import path from 'node:path';
import { createRequire } from 'node:module';
const require = createRequire(import.meta.url);
const { analyze, RULES } = require('../dist/index.js');

const root = path.resolve(path.dirname(new URL(import.meta.url).pathname), '..', 'corpus');
const labels = JSON.parse(fs.readFileSync(path.join(root, 'labels.json'), 'utf8'));
const sets = { real: {}, fixtures: {} };
for (const set of Object.keys(sets)) {
  for (const f of fs.readdirSync(path.join(root, set)).filter((f) => f.endsWith('.pine')).sort()) {
    const rel = `${set}/${f}`;
    const src = fs.readFileSync(path.join(root, rel), 'utf8');
    let expected = [];
    if (set === 'real') expected = (labels[rel] ?? []).map((e) => `${e.rule}@${e.line}`);
    else src.split('\n').forEach((l, i) => { for (const m of l.matchAll(/expect:\s*((?:PRC\d{3}[ ,]*)+)/g)) m[1].match(/PRC\d{3}/g).forEach((r) => expected.push(`${r}@${i + 1}`)); });
    const got = [...new Set(analyze(src, rel).map((x) => `${x.ruleId}@${x.line}`))];
    sets[set][rel] = { expected, got };
  }
}
const stats = (files) => {
  const s = {};
  for (const id of Object.keys(RULES)) s[id] = { tp: 0, fp: 0, fn: 0 };
  const misses = [];
  for (const [f, { expected, got }] of Object.entries(files)) {
    for (const g of got) { const r = g.split('@')[0]; if (expected.includes(g)) s[r].tp++; else { s[r].fp++; misses.push(`FP ${f}:${g}`); } }
    for (const e of expected) if (!got.includes(e)) { s[e.split('@')[0]].fn++; misses.push(`FN ${f}:${e}`); }
  }
  return { s, misses };
};
const pct = (a, b) => (b === 0 ? 'n/a' : `${((100 * a) / b).toFixed(0)}% (${a}/${b})`);
let md = '';
for (const name of ['real', 'fixtures', 'all']) {
  const files = name === 'all' ? { ...sets.real, ...sets.fixtures } : sets[name];
  const { s, misses } = stats(files);
  md += `\n### ${name} (${Object.keys(files).length} files)\n\n| rule | TP | FP | FN | precision | recall |\n|---|---|---|---|---|---|\n`;
  for (const [id, v] of Object.entries(s)) md += `| ${id} ${RULES[id].name} | ${v.tp} | ${v.fp} | ${v.fn} | ${pct(v.tp, v.tp + v.fp)} | ${pct(v.tp, v.tp + v.fn)} |\n`;
  if (misses.length && name !== 'all') md += `\nMismatches:\n${misses.map((m) => `- ${m}`).join('\n')}\n`;
}
console.log(md);
if (process.argv.includes('--write')) fs.writeFileSync(path.join(root, 'RESULTS.md'), `# Corpus evaluation\n\nGenerated by \`npm run eval -- --write\`. Location match = same rule on the same line.\n${md}`);
